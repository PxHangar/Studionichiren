"""Regenerate the SQL policy from the same reference list used by the app.
Usage: python scripts/build-name-policy-migration.py <CLI-generated migration.sql>
"""
import json, pathlib, sys
root=pathlib.Path(__file__).resolve().parents[1]
policy=json.loads((root/'lib/public-name-policy.json').read_text())
def q(s):return "'"+s.replace("'","''")+"'"
def arr(items):return 'array['+','.join(q(s) for s in items)+']::text[]'
conf=policy['confusables'];digits=policy['digits']
sql=f'''-- Generated by scripts/build-name-policy-migration.py from lib/public-name-policy.json.
-- Validates only public display names, never email addresses or authorization metadata.
begin;
create or replace function public.community_name_allowed(value text)
returns boolean language sql immutable parallel safe security invoker set search_path='' as $policy$
 with original as (
  select lower(normalize(coalesce(value,''),NFKD)) as name
 ), folded as (
  select name, regexp_replace(translate(name,{q(''.join(conf))},{q(''.join(conf.values()))}),'[̀-ͯ]','','g') as text from original
 ), forms as (
  select name, regexp_replace(translate(text,{q(''.join(digits))},{q(''.join(digits.values()))}),'[^a-z]','','g') as compact,
  regexp_split_to_array(regexp_replace(text,'[^a-z]+',' ','g'),' +') as words from folded
 )
 select coalesce(char_length(btrim(value)) between 2 and 60 and value ~ '[[:alnum:]]'
  and not exists(select 1 from unnest({arr(policy['fragments'])}) term where strpos(compact,term)>0)
  and not exists(select 1 from unnest({arr(policy['words'])}) term where term=any(words) or compact=term)
  and not exists(select 1 from unnest({arr(policy['scripts'])}) term where strpos(name,normalize(term,NFKD))>0),false)
 from forms;
$policy$;
revoke all on function public.community_name_allowed(text) from public,anon;
grant execute on function public.community_name_allowed(text) to authenticated,service_role;
-- The existing signup trigger creates a profile in the same transaction. A forbidden
-- profile name therefore rejects both direct signups and later profile/API updates.
alter table public.profiles add constraint community_public_name_policy check(public.community_name_allowed(display_name));
commit;
'''
target=pathlib.Path(sys.argv[1]);target.write_text(sql)
print(target)
